"""Build the Goa trip-story map: toned OSM tiles + one OSRM route per trip day.

Run: python scripts/media/build-goa-trip-map.py apps/web/public/maps apps/web/src/lib

Writes <public>/maps/goa-trip-map.jpg and <lib>/goa-trip-route.ts (generated geometry).
Tiles: (c) OpenStreetMap contributors (ODbL). Routes: OSRM demo server.
"""
import io
import json
import math
import sys
import time
import urllib.request

from PIL import Image, ImageEnhance, ImageOps

PUBLIC, LIB = sys.argv[1], sys.argv[2]
UA = {"User-Agent": "SaayroDev/0.1 (one-off static asset build)"}
Z = 14
OUT_SCALE = 0.8
LAT_MIN, LAT_MAX = 15.362, 15.628
LON_MIN, LON_MAX = 73.712, 73.942

PLACES = {
    "dabolim": ("Dabolim Airport", 15.3808, 73.8314),
    "assagao": ("Casa Saudade, Assagao", 15.5946, 73.7661),
    "anjuna": ("Anjuna", 15.5736, 73.7410),
    "vagator": ("Vagator", 15.6005, 73.7339),
    "chapora": ("Chapora Fort", 15.6063, 73.7363),
    "aguada": ("Fort Aguada", 15.4920, 73.7733),
    "fontainhas": ("Fontainhas, Panjim", 15.4980, 73.8322),
}
LEGS = [
    ["dabolim", "assagao"],
    ["assagao", "anjuna", "vagator", "chapora"],
    ["assagao", "aguada"],
    ["assagao", "fontainhas"],
    ["assagao", "dabolim"],
]


def to_px(lat: float, lon: float) -> tuple[float, float]:
    n = 2 ** Z * 256
    x = (lon + 180) / 360 * n
    y = (1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2 * n
    return x, y


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


x0, y0 = to_px(LAT_MAX, LON_MIN)
x1, y1 = to_px(LAT_MIN, LON_MAX)
tx0, ty0, tx1, ty1 = int(x0 // 256), int(y0 // 256), int(x1 // 256), int(y1 // 256)
canvas = Image.new("RGB", ((tx1 - tx0 + 1) * 256, (ty1 - ty0 + 1) * 256))
for tx in range(tx0, tx1 + 1):
    for ty in range(ty0, ty1 + 1):
        tile = Image.open(io.BytesIO(fetch(f"https://tile.openstreetmap.org/{Z}/{tx}/{ty}.png"))).convert("RGB")
        canvas.paste(tile, ((tx - tx0) * 256, (ty - ty0) * 256))
        time.sleep(0.05)

crop = canvas.crop((int(x0 - tx0 * 256), int(y0 - ty0 * 256), int(x1 - tx0 * 256), int(y1 - ty0 * 256)))
toned = ImageEnhance.Contrast(ImageEnhance.Color(crop).enhance(0.45)).enhance(0.92)
warm = ImageOps.colorize(ImageOps.grayscale(toned), black="#3c3654", white="#fbf4ea", mid="#d9c6aa")
final = Image.blend(warm, toned, 0.35)
mask = Image.new("L", crop.size, 0)
src_px, mask_px = crop.load(), mask.load()
for yy in range(crop.height):
    for xx in range(crop.width):
        pr, pg, pb = src_px[xx, yy]
        if abs(pr - 170) < 14 and abs(pg - 211) < 14 and abs(pb - 223) < 14:
            mask_px[xx, yy] = 255
final = Image.composite(Image.new("RGB", crop.size, "#cfe8e4"), final, mask)
final = final.resize((round(crop.width * OUT_SCALE), round(crop.height * OUT_SCALE)), Image.LANCZOS)
final.save(f"{PUBLIC}/goa-trip-map.jpg", quality=80, optimize=True, progressive=True)


def px(lat: float, lon: float) -> tuple[float, float]:
    x, y = to_px(lat, lon)
    return round((x - x0) * OUT_SCALE, 1), round((y - y0) * OUT_SCALE, 1)


legs_out = []
for leg in LEGS:
    coords = ";".join(f"{PLACES[k][2]},{PLACES[k][1]}" for k in leg)
    route = json.loads(fetch(f"https://router.project-osrm.org/route/v1/driving/{coords}?overview=full&geometries=geojson"))["routes"][0]
    pts = [px(lat, lon) for lon, lat in route["geometry"]["coordinates"]]
    pts = pts[:: max(1, len(pts) // 160)] + [pts[-1]]
    d = "M" + " L".join(f"{x} {y}" for x, y in pts)
    legs_out.append({"stops": leg, "distanceKm": round(route["distance"] / 1000, 1),
                     "durationMin": round(route["duration"] / 60), "path": d})
    time.sleep(1)

places_out = {k: {"name": v[0], "x": px(v[1], v[2])[0], "y": px(v[1], v[2])[1]} for k, v in PLACES.items()}
ts = f"""/**
 * Generated by scripts/media/build-goa-trip-map.py. Do not edit by hand.
 * Map: (c) OpenStreetMap contributors (ODbL), toned for Golden Hour. Routes: OSRM.
 * Coordinates are pixels in /maps/goa-trip-map.jpg.
 */
export const goaTripMap = {{
  src: "/maps/goa-trip-map.jpg",
  width: {final.width},
  height: {final.height},
  places: {json.dumps(places_out)},
  legs: {json.dumps(legs_out)}
}} as const;

export type GoaTripPlace = keyof typeof goaTripMap.places;
"""
with open(f"{LIB}/goa-trip-route.ts", "w", encoding="utf-8") as f:
    f.write(ts)
print(final.size, [(l["stops"], l["distanceKm"], l["durationMin"]) for l in legs_out])

